        <section>
          <h2>6. 친환경 대응 — rPET·바이오플라스틱 비용과 인증</h2>
          <p>
            ESG 경영과 포장재 재활용 의무화(자원재활용법), 수출 시 EU 포장재
            규정(PPWR) 대응을 위해 친환경 플라스틱 용기 수요가 증가하고 있습니다.
            현재 국내에서 적용 가능한 주요 옵션은 다음과 같습니다.
          </p>
          <ul>
            <li>
              <strong>rPET(재활용 PET)</strong> — 버진 PET 대비 10~25% 추가
              비용이 일반적입니다. GRS(Global Recycled Standard) 인증 획득에는
              3~6개월이 소요됩니다. EU 수출 제품의 경우 2030년까지 재활용 원료
              함량 의무 비율이 강화될 예정이므로, 지금부터 rPET 공급망을 확보해
              두는 것이 중요합니다.
            </li>
            <li>
              <strong>바이오플라스틱(PLA 등)</strong> — 버진 소재 대비 50~100%
              이상 비용이 상승합니다. 산업용 퇴비화(industrial composting)
              조건에서만 분해되며, 일반 가정 매립·소각 환경에서는 일반
              플라스틱과 분해 속도 차이가 크지 않습니다. 환경부
              친환경마크(EL724) 인증 여부를 확인하십시오.
            </li>
            <li>
              <strong>단일 소재(Mono-material) 용기</strong> — PP 또는 HDPE
              단일 소재로 용기와 뚜껑을 통일하면 재활용률이 높아집니다. 복합
              소재 결합 구조를 피해 분리배출 용이성을 높이는 방향입니다.
            </li>
          </ul>
          <p>
            rPET 도입 시 식약처의 식품 접촉 적합성(재생 원료 이행성 시험)을
            별도로 확인해야 합니다. 재활용 원료는 오염 이력에 따라 식품 접촉용
            사용이 제한될 수 있습니다.
          </p>
        </section>

